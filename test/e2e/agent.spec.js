  await page.getByLabel("Nombre del nuevo proveedor").fill(supplier)
  await page.getByRole("button", { name: "Crear proveedor y conservar revisión" }).click()
  await expect(page.getByLabel("Título", { exact: true })).toHaveValue(title)
  await expect(page.getByLabel("Salida", { exact: true })).toHaveValue("03/02/2030")
  await expect(page.getByLabel("Proveedor", { exact: true })).toHaveValue(/.+/)
