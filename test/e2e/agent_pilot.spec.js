const { test, expect } = require("@playwright/test")
const path = require("path")
const fs = require("fs")
const base = `http://localhost:${process.env.E2E_PORT || "3100"}`
const auth = base.replace("localhost", "auth.localhost")
test.use({ actionTimeout: 10000 })

test("pilot lifecycle: simulated Google, PDF departures, private agenda, expiry and operator renewal", async ({ page, browser }, testInfo) => {
  test.setTimeout(120000)
  await page.goto(`${auth}/test/pro-lifecycle/prepare`)
  const identity = JSON.parse(await page.locator("body").innerText())
  await page.goto(`${base}/agente/alta`)
  await page.getByRole("button", { name: "Ingresar con Google" }).click()
  await expect(page).toHaveURL(/auth\.localhost.*\/auth\/continue/)
  await page.getByRole("button", { name: "Ingresar con Google" }).click()
  await expect(page).toHaveURL(`${base}/agente/alta`)
  const slug = `piloto-${testInfo.project.name}-${Date.now()}`
  await page.getByLabel("Nombre", { exact: true }).fill(`Piloto ${slug}`)
  await page.getByLabel("Link público", { exact: true }).fill(slug)
  await page.getByLabel("WhatsApp con código de país").fill("5491155551234")
  await page.getByRole("button", { name: "Crear mi espacio" }).click()
  await expect(page).toHaveURL(`${base}/agente`)
  const initial = await (await page.request.get(`${base}/test/pro-lifecycle`)).json()
  expect(initial.trial_seconds).toBe(14 * 86400)
  expect(initial.price_cents).toBe(1900)
  expect(initial.status).toBe("trialing")
  expect(initial.memberships.length).toBe(2)

  await page.goto(`${base}/agente/empresas/new`)
  await page.getByLabel("Nombre del proveedor").fill(`Privado ${slug}`)
  await page.getByLabel("Notas internas").fill("PROVEEDOR-PRIVADO-PILOTO")
  await page.getByRole("button", { name: "Guardar proveedor" }).click()
  await page.goto(`${base}/agente/importaciones`)
  await page.getByLabel("Archivo a importar").setInputFiles(path.join(__dirname, "../fixtures/files/agent.pdf"))
  await page.getByRole("button", { name: "Procesar con IA" }).click()
  await expect(page.getByRole("link", { name: "Revisar ficha" })).toHaveCount(4)
  const reviewUrls = await page.getByRole("link", { name: "Revisar ficha" }).evaluateAll(links => links.map(link => link.href))
  const title = `Córdoba corregida ${slug}`
  const trips = []
  for (let index = 0; index < 2; index++) {
    await page.goto(reviewUrls[index])
    await page.getByLabel("Proveedor", { exact: true }).selectOption({ label: `Privado ${slug}` })
    await page.getByLabel("Título", { exact: true }).fill(index === 0 ? title : `Otro borrador ${slug}`)
    await page.getByLabel("Salida", { exact: true }).fill(index === 0 ? "03/02/2030" : "10/02/2030")
    await page.getByRole("button", { name: "Guardar borrador" }).click()
    await expect(page.getByRole("button", { name: "Publicar revisión", exact: true })).toBeVisible()
    trips.push(page.url())
  }
  await page.goto(trips[0])
  await page.getByRole("button", { name: "Publicar revisión", exact: true }).click()
  const publicContext = await browser.newContext()
  const visitor = await publicContext.newPage()
  try {
    await visitor.goto(`${base}/${slug}`)
    await visitor.getByRole("combobox", { name: "Destino", exact: true }).click()
    await visitor.getByRole("option", { name: "Córdoba", exact: true }).click()
    await expect(visitor).toHaveURL(/destination=/)
    await visitor.getByText("Más filtros de viajes", { exact: true }).click()
    await expect(visitor.locator("details.agent-catalog-filters")).toHaveAttribute("open", "")
    await visitor.getByLabel("Desde", { exact: true }).fill("01/02/2030")
    await visitor.getByLabel("Hasta", { exact: true }).fill("04/02/2030")
    await visitor.getByRole("button", { name: "Filtrar", exact: true }).click()
    await expect(visitor).toHaveURL(/from=2030-02-01/)
    await visitor.getByRole("link", { name: title, exact: true }).click()
    await expect(visitor).toHaveURL(/\/viajes\//)
    await expect(visitor.getByRole("heading", { name: title, exact: true })).toBeVisible()
    const publicUrl = visitor.url()
    const whatsapp = new URL(await visitor.getByRole("link", { name: "Consultar por WhatsApp" }).getAttribute("href"))
    expect(whatsapp.pathname).toBe("/5491155551234")
    expect(whatsapp.searchParams.get("text")).toContain(title)
    expect(whatsapp.searchParams.get("text")).toContain("03/02/2030")
    expect(whatsapp.searchParams.get("text")).toContain(publicUrl)
    await expect(visitor.locator("body")).not.toContainText("PROVEEDOR-PRIVADO-PILOTO")
    await page.getByRole("link", { name: "Editar viaje", exact: true }).click()
    await page.getByLabel("Título del viaje").fill(`REVISION-PRIVADA ${slug}`)
    await page.getByRole("button", { name: "Guardar borrador / revisión" }).click()

    await page.goto(`${base}/agente/clientes/new`)
    await page.getByLabel("Nombre", { exact: true }).fill(`=CLIENTE-PRIVADO ${slug}`)
    await page.getByLabel("Teléfono / WhatsApp con código de país").fill("5491144443333")
    await page.getByRole("button", { name: "Guardar cliente" }).click()
    await expect(page.getByLabel("Nota privada", { exact: true })).toBeVisible()
    const clientUrl = page.url()
    await page.getByLabel("Nota privada", { exact: true }).fill("+NOTA-PRIVADA-PILOTO")
    await page.getByRole("button", { name: "Guardar nota" }).click()
    await expect(page.getByText("+NOTA-PRIVADA-PILOTO", { exact: true })).toBeVisible()
    await page.goto(`${base}/agente/clientes`)
    for (const [label, content] of [["Exportar contactos", "'=CLIENTE-PRIVADO"], ["Exportar notas", "'+NOTA-PRIVADA-PILOTO"]]) {
      const downloading = page.waitForEvent("download")
      await page.getByRole("link", { name: label, exact: true }).click()
      const download = await downloading
      expect(fs.readFileSync(await download.path(), "utf8")).toContain(content)
    }
    const csrf = await page.locator('meta[name="csrf-token"]').getAttribute("content")
    expect((await page.request.post(`${base}/test/pro-lifecycle/expire`, { headers: { "X-CSRF-Token": csrf } })).status()).toBe(204)
    expect((await visitor.goto(publicUrl)).status()).toBe(404)
    expect((await page.request.get(`${base}/agente/viajes/new`)).status()).toBe(403)
    expect((await page.request.post(`${trips[0]}/publish`, { headers: { "X-CSRF-Token": csrf } })).status()).toBe(403)
    expect((await page.request.post(`${base}/agente/importaciones`, { headers: { "X-CSRF-Token": csrf } })).status()).toBe(403)
    await page.goto(clientUrl)
    await expect(page.getByText("+NOTA-PRIVADA-PILOTO", { exact: true })).toBeVisible()
    const exported = await page.request.get(`${base}/agente/export.json`)
    expect(exported.status()).toBe(200)
    expect(exported.headers()["cache-control"]).toContain("no-store")
    expect((await exported.json()).clients[0].notes[0].body).toBe("+NOTA-PRIVADA-PILOTO")

    const operator = await publicContext.newPage()
    await operator.goto(`${base}/test/sign-in?email=${encodeURIComponent(identity.operator_email)}`)
    await operator.goto(`${base}/platform/agent_workspaces`)
    const account = operator.locator("section").filter({ has: operator.getByRole("heading", { name: `Piloto ${slug}`, exact: true }) })
    await account.getByRole("button", { name: "Activar / renovar un mes" }).click()
    await expect(operator.getByText("Se agregó un mes de Pro manualmente.", { exact: true })).toBeVisible()
    // Use a new anonymous context after the operator's separate session.
    const anonymous = await browser.newContext()
    const restored = await anonymous.newPage()
    expect((await restored.goto(publicUrl)).status()).toBe(200)
    await expect(restored.getByRole("heading", { name: title, exact: true })).toBeVisible()
    await restored.goto(`${base}/${slug}`)
    await expect(restored.getByRole("link", { name: `Otro borrador ${slug}`, exact: true })).toHaveCount(0)
    await expect(restored.locator("body")).not.toContainText("REVISION-PRIVADA")
    await anonymous.close()
    const final = await (await page.request.get(`${base}/test/pro-lifecycle`)).json()
    expect(final.status).toBe("active")
    expect(final.memberships).toEqual(initial.memberships)
    expect(final.price_cents).toBe(initial.price_cents)
    await operator.goto(`${base}/test/sign-in?email=agente-otro%40turistack.local`)
    expect((await operator.request.get(clientUrl)).status()).toBe(404)
    expect((await operator.request.get(`${trips[0]}/source`)).status()).toBe(404)
    const otherExport = await operator.request.get(`${base}/agente/export.json`)
    expect(await otherExport.text()).not.toContain("CLIENTE-PRIVADO")
  } finally {
    await publicContext.close()
  }
})
