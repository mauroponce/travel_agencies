const { test, expect } = require("@playwright/test")
const path = require("path")
const fs = require("fs")
const port = process.env.E2E_PORT || "3100"
const base = `http://agente.lvh.me:${port}`

test("reseller publishes original flyer, filters public catalog and shares with copy and download fallbacks", async ({ page, browser }, testInfo) => {
  await page.addInitScript(() => {
    // Native OS sharing and secure context are simulated on the local HTTP host.
    Object.defineProperty(window, "isSecureContext", { configurable: true, value: true })
    window.sharedPayload = null
    window.shareBehavior = "ok"
    Object.defineProperty(navigator, "canShare", { configurable: true, value: data => (window.shareBehavior !== "no-combination" || (!data.text && !data.url)) && (window.shareBehavior !== "no-url" || !data.url) && window.shareBehavior !== "unsupported" && Array.isArray(data.files) && data.files[0] instanceof File })
    Object.defineProperty(navigator, "share", { configurable: true, value: async data => {
      if (window.shareBehavior === "cancel") throw new DOMException("cancel", "AbortError")
      if (window.shareBehavior === "error") throw new DOMException("sharing denied", "NotAllowedError")
      window.sharedPayload = { text: data.text, url: data.url, name: data.files[0].name, type: data.files[0].type, bytes: Array.from(new Uint8Array(await data.files[0].arrayBuffer())) }
    } })
    Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText: async text => { window.copiedText = text } } })
  })
  await page.goto(`${base}/test/sign-in?email=agente%40turistack.local`)
  await page.goto(`${base}/agente/viajes/new`)
  const title = `Bariloche flyer ${testInfo.project.name}`
  await page.getByLabel("O crear un proveedor nuevo").fill(`Carlos Sansot ${testInfo.project.name}`)
  await page.getByLabel("Título del viaje").fill(title)
  await page.getByLabel("Destino", { exact: true }).fill("Bariloche")
  await page.getByLabel("Fecha de salida").fill("10/10/2027")
  await page.getByLabel("Precio final del proveedor").fill("450.000,50")
  await page.getByLabel("Flyer original", { exact: false }).setInputFiles(path.join(__dirname, "../fixtures/files/agent.png"))
  await page.getByRole("button", { name: "Guardar y publicar" }).click()
  await expect(page.getByRole("heading", { name: title, exact: true })).toBeVisible()
  const share = page.getByRole("button", { name: "Compartir flyer en WhatsApp" })
  await expect(share).toBeEnabled()
  await share.click()
  await expect.poll(() => page.evaluate(() => window.sharedPayload?.type)).toBe("image/png")
  const payload = await page.evaluate(() => window.sharedPayload)
  expect(payload.bytes).toEqual(Array.from(fs.readFileSync(path.join(__dirname, "../fixtures/files/agent.png"))))
  expect(payload.text).toContain(payload.url)
  expect(payload.url).toMatch(/\/viajes\/[a-z0-9_-]+$/)
  await expect(page.getByText("Menú de compartir cerrado.", { exact: false })).toBeVisible()
  await page.getByRole("button", { name: "Copiar enlace", exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.copiedText)).toBe(payload.url)
  await page.getByRole("button", { name: "Copiar texto para estado" }).click()
  await expect.poll(() => page.evaluate(() => window.copiedText)).toBe(payload.text)
  const downloaded = page.waitForEvent("download")
  await page.getByRole("link", { name: "Descargar flyer", exact: true }).click()
  const download = await downloaded
  expect(fs.readFileSync(await download.path())).toEqual(Buffer.from(payload.bytes))
  for (const [behavior, text] of [["cancel", "Se canceló el menú"], ["error", "No se pudo compartir"], ["unsupported", "Este navegador no permite"]]) {
    await page.evaluate(value => { window.shareBehavior = value }, behavior)
    await share.click()
    await expect(page.getByRole("status").filter({ hasText: text })).toBeVisible()
  }
  await page.evaluate(() => { window.sharedPayload = null; window.shareBehavior = "ok" })
  await share.click()
  await expect.poll(() => page.evaluate(() => window.sharedPayload?.name)).toBe("flyer.png")
  await page.evaluate(() => { window.sharedPayload = null; window.shareBehavior = "no-url" })
  await share.click()
  await expect.poll(() => page.evaluate(() => window.sharedPayload?.text)).toContain(payload.url)
  expect(await page.evaluate(() => window.sharedPayload.url)).toBeUndefined()
  await page.evaluate(() => { window.sharedPayload = null; window.shareBehavior = "no-combination" })
  await share.click()
  await expect(page.getByRole("status").filter({ hasText: "imagen y el texto juntos" })).toBeVisible()
  expect(await page.evaluate(() => window.sharedPayload)).toBeNull()
  await page.evaluate(() => { Object.defineProperty(navigator, "share", { configurable: true, value: undefined }) })
  await share.click()
  await expect(page.getByRole("status").filter({ hasText: "Este navegador no permite" })).toBeVisible()
  await page.evaluate(() => { Object.defineProperty(window, "isSecureContext", { configurable: true, value: false }); window.shareBehavior = "ok" })
  await share.click()
  await expect(page.getByRole("status").filter({ hasText: "Este navegador no permite" })).toBeVisible()
  await page.evaluate(() => { Object.defineProperty(navigator, "clipboard", { configurable: true, value: undefined }) })
  await page.getByRole("button", { name: "Copiar enlace", exact: true }).click()
  await expect(page.getByLabel("Texto para copiar manualmente")).toHaveValue(payload.url)
  const visitorContext = await browser.newContext({ viewport: testInfo.project.use.viewport })
  const visitor = await visitorContext.newPage()
  await visitor.goto(base)
  await visitor.getByRole("combobox", { name: "Destino", exact: true }).click()
  await visitor.getByRole("option", { name: "Bariloche", exact: true }).click()
  await expect(visitor).toHaveURL(/destination=Bariloche/)
  await visitor.getByText("Más filtros de viajes", { exact: true }).click()
  await visitor.getByLabel("Moneda", { exact: true }).selectOption("ARS")
  await visitor.getByLabel("Unidad del precio", { exact: true }).selectOption("per_person")
  await visitor.getByLabel("Precio máximo", { exact: true }).fill("500000")
  await visitor.getByRole("button", { name: "Filtrar", exact: true }).click()
  await visitor.getByRole("link", { name: title, exact: true }).click()
  await expect(visitor).toHaveURL(payload.url)
  await expect(visitor.getByRole("img", { name: title, exact: true })).toBeVisible()
  await expect(visitor.getByRole("link", { name: "Consultar por WhatsApp" })).toHaveAttribute("href", /wa\.me\/5491155550303\?text=.*viajes/)
  expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await visitorContext.close()
  await page.getByRole("button", { name: "Despublicar", exact: true }).click()
  await expect(page.getByText("Viaje despublicado.", { exact: true })).toBeVisible()
  const publicPage = await page.context().newPage()
  const response = await publicPage.goto(payload.url)
  expect(response.status()).toBe(404)
})

test("agency availability polling updates rendered price and seats", async ({ page }) => {
  await page.goto("/viajes/mendoza-super-sale")
  const url = await page.locator("[data-availability-url-value]").getAttribute("data-availability-url-value")
  expect(url).toBe("/viajes/mendoza-super-sale/status")
  await page.route(`**${url}`, route => route.fulfill({ contentType: "application/json", body: JSON.stringify({ price_cents: 76543200, service_fee_cents: 10000, available_seats: 0, sold_out: true, promotion_label: "Tarifa actualizada" }) }))
  await page.evaluate(() => document.dispatchEvent(new Event("visibilitychange")))
  await expect(page.locator('[data-availability-target="price"]')).toContainText("765.432")
  await expect(page.locator('[data-availability-target="seats"]')).toHaveText("Sin cupos disponibles")
  await expect(page.locator('[data-availability-target="label"]')).toHaveText("Tarifa actualizada")
})


test("sharing waits for the actual image and offers fallbacks when preparation fails", async ({ page }) => {
  await page.goto(`${base}/test/sign-in?email=agente%40turistack.local`)
  await page.goto(`${base}/agente/viajes`)
  await page.goto(`${base}/agente/viajes/new`)
  await page.getByLabel("Proveedor", { exact: true }).selectOption({ label: "Proveedor demo" })
  await page.getByLabel("Título del viaje").fill("Preparar imagen")
  await page.getByLabel("Destino", { exact: true }).fill("Salta")
  await page.getByLabel("Fecha de salida").fill("10/10/2027")
  await page.getByLabel("Precio final del proveedor").fill("450000")
  await page.getByLabel("Flyer original", { exact: false }).setInputFiles(path.join(__dirname, "../fixtures/files/agent.png"))
  await page.getByRole("button", { name: "Guardar y publicar" }).click()
  await expect(page.getByRole("heading", { name: "Preparar imagen", exact: true })).toBeVisible()
  const url = page.url()
  let release
  const blocked = new Promise(resolve => { release = resolve })
  await page.route("**/agente/viajes/*/cover?*", async route => { await blocked; await route.continue() })
  await page.goto(url)
  const share = page.getByRole("button", { name: "Compartir flyer en WhatsApp" })
  await expect(share).toBeDisabled()
  await expect(share).toHaveAttribute("aria-busy", "true")
  await expect(page.getByRole("link", { name: "Descargar flyer", exact: true })).toBeVisible()
  release()
  await expect(share).toBeEnabled()
  await page.unroute("**/agente/viajes/*/cover?*")
  await page.route("**/agente/viajes/*/cover?*", route => route.fulfill({ status: 403, body: "denied" }))
  await page.reload()
  await expect(share).toBeEnabled()
  await expect(page.getByRole("status").filter({ hasText: "No pudimos preparar" })).toBeVisible()
  await page.getByRole("button", { name: "Copiar enlace", exact: true }).click()
  await expect(page.getByRole("status").filter({ hasText: /Enlace copiado|texto seleccionado/ })).toBeVisible()
})

for (const [filename, mime] of [["agent.jpg", "image/jpeg"], ["agent.webp", "image/webp"], ["agent.pdf", "image/jpeg"]]) {
  test(`shares real ${filename} bytes and keeps the original download`, async ({ page }) => {
    await page.addInitScript(() => {
      Object.defineProperty(window, "isSecureContext", { configurable: true, value: true })
      Object.defineProperty(navigator, "canShare", { configurable: true, value: () => true })
      Object.defineProperty(navigator, "share", { configurable: true, value: async data => {
        window.sharedFlyer = { type: data.files[0].type, text: data.text, bytes: Array.from(new Uint8Array(await data.files[0].arrayBuffer())) }
      } })
    })
    await page.goto(`${base}/test/sign-in?email=agente%40turistack.local`)
    await page.goto(`${base}/agente/viajes/new`)
    await page.getByLabel("Proveedor", { exact: true }).selectOption({ label: "Proveedor demo" })
    await page.getByLabel("Título del viaje").fill(`Flyer ${filename}`)
    await page.getByLabel("Destino", { exact: true }).fill("Salta")
    await page.getByLabel("Fecha de salida").fill("10/10/2027")
    await page.getByLabel("Precio final del proveedor").fill("450000")
    await page.getByLabel("Flyer original", { exact: false }).setInputFiles(path.join(__dirname, "../fixtures/files", filename))
    await page.getByRole("button", { name: "Guardar y publicar" }).click()
    const share = page.getByRole("button", { name: "Compartir flyer en WhatsApp" })
    await expect(share).toBeEnabled()
    await share.click()
    await expect.poll(() => page.evaluate(() => window.sharedFlyer?.type)).toBe(mime)
    const payload = await page.evaluate(() => window.sharedFlyer)
    expect(payload.text).toMatch(/\/viajes\/[a-z0-9]+/)
    const downloaded = page.waitForEvent("download")
    await page.getByRole("link", { name: "Descargar flyer", exact: true }).click()
    expect(fs.readFileSync(await (await downloaded).path())).toEqual(Buffer.from(payload.bytes))
    if (filename.endsWith("pdf")) expect(payload.bytes.slice(0, 3)).toEqual([255, 216, 255])
    else expect(payload.bytes).toEqual(Array.from(fs.readFileSync(path.join(__dirname, "../fixtures/files", filename))))
    const source = await page.request.get(page.url() + "/source")
    expect(source.status()).toBe(200)
    expect(await source.body()).toEqual(fs.readFileSync(path.join(__dirname, "../fixtures/files", filename)))
  })
}
