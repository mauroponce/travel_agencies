const { test, expect } = require("@playwright/test")
const path = require("path")
const base = `http://localhost:${process.env.E2E_PORT || "3100"}`
test.use({ actionTimeout: 10000 })

async function startWizard(page, testInfo, supplierName) {
  const identity = await (await page.request.get(`${base.replace("localhost", "auth.localhost")}/test/pro-lifecycle/prepare`)).json()
  await page.goto(`${base}/test/sign-in?email=${encodeURIComponent(identity.email)}&purpose=agent_onboarding`)
  await page.getByLabel("Nombre", { exact: true }).fill("Asesor importador")
  await page.getByLabel("Link público", { exact: true }).fill(`importador-${Date.now()}-${testInfo.project.name}`)
  await page.getByLabel("WhatsApp con código de país").fill("5491155551234")
  await page.getByRole("button", { name: "Crear mi espacio" }).click()
  await expect(page.getByRole("heading", { name: "Todo listo para tu próximo viaje" })).toBeVisible()
  await page.goto(`${base}/asesor/empresas/nuevo`)
  await page.getByLabel("Nombre del proveedor").fill(supplierName)
  await page.getByRole("button", { name: "Guardar proveedor" }).click()
  await expect(page.getByRole("heading", { name: supplierName, exact: true })).toBeVisible()
  await page.goto(`${base}/asesor/viajes`)
  await page.getByRole("link", { name: "Importar con IA", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Crear viajes desde un flyer" })
  await expect(dialog).toBeVisible()
  return dialog
}

test("flyer wizard resumes shared and individual corrections and creates selected independent drafts", async ({ page }, testInfo) => {
  test.setTimeout(120000)
  const errors = []
  page.on("pageerror", error => errors.push(error.message))
  const dialog = await startWizard(page, testInfo, "Carlos Sansot Viajes")
  await dialog.getByLabel("Archivo a importar").setInputFiles(path.join(__dirname, "../fixtures/files/agent_sansot.jpeg"))
  await dialog.getByRole("button", { name: "Procesar con IA", exact: true }).click()
  await expect(dialog.getByRole("heading", { name: "Revisá la información extraída" })).toBeVisible()
  await expect(dialog.getByLabel("Empresa organizadora", { exact: true }).locator("option:checked")).toHaveText("Carlos Sansot Viajes")
  await expect(dialog.getByLabel("Hotel", { exact: true })).toHaveValue("Gran Victoria")
  await expect(dialog.getByLabel("Tarifas, suplementos y condiciones")).toContainText("$15.000 adicionales")
  await expect(dialog.getByLabel("Provincia o región")).toHaveCount(0)
  await expect(dialog.getByLabel("Unidad del precio")).toHaveCount(0)
  const tariffs = dialog.locator(".ai-fares")
  await expect(tariffs.getByRole("tab")).toHaveCount(2)
  await tariffs.getByRole("tab", { name: "Base doble", exact: true }).click()
  const double = tariffs.getByRole("tabpanel", { name: "Base doble", exact: true })
  await expect(double.getByLabel("Precio final del proveedor")).toHaveValue("115000.00")
  await expect(double.getByLabel("Precio de lista (opcional)")).toHaveValue("143750.00")
  await expect(double.getByLabel("Moneda")).toHaveValue("ARS")
  await expect(double.getByLabel("Moneda").locator("option")).toHaveText(["Pesos Argentinos", "Dólares"])
  await double.getByLabel("Precio final del proveedor").fill("116000")
  await tariffs.getByRole("tab", { name: "Base triple / cuádruple", exact: true }).click()
  const triple = tariffs.getByRole("tabpanel", { name: "Base triple / cuádruple", exact: true })
  await expect(triple.getByLabel("Precio final del proveedor")).toHaveValue("105000.00")
  await page.screenshot({ path: testInfo.outputPath("wizard-fare-tabs.png") })
  await dialog.getByLabel("Hotel", { exact: true }).fill("Hotel compartido")
  await page.screenshot({ path: testInfo.outputPath("wizard-shared.png") })
  await dialog.getByRole("button", { name: "Revisar viajes y fechas" }).click()
  await expect(dialog.getByText("6 viajes seleccionados para crear", { exact: true })).toBeVisible()
  await expect(dialog.locator(".ai-review-row")).toHaveCount(6)
  await dialog.getByRole("button", { name: "Editar ↓", exact: true }).first().click()
  await dialog.getByLabel("Nombre del viaje", { exact: true }).fill("Carlos Paz personalizado")
  await dialog.getByLabel("Hotel", { exact: true }).fill("Hotel particular")
  const personalizedTariff = dialog.locator(".ai-review-row").first().locator(".ai-fare-panel").first()
  await personalizedTariff.getByLabel("Precio final del proveedor").fill("104000")
  await dialog.locator("[data-enabled]").nth(1).uncheck()
  await expect(dialog.getByText("5 viajes seleccionados para crear", { exact: true })).toBeVisible()
  await dialog.getByRole("button", { name: "Atrás", exact: true }).click()
  await dialog.getByLabel("Hotel", { exact: true }).fill("Hotel actualizado")
  await dialog.locator(".ai-fare-panel").first().getByLabel("Precio final del proveedor").fill("106000")
  await dialog.getByRole("button", { name: "Revisar viajes y fechas" }).click()
  await expect(dialog.getByLabel(/^Hotel(?:\s+Personalizado)?$/)).toHaveValue("Hotel particular")
  await expect(dialog.getByLabel(/^Nombre del viaje/)).toHaveValue("Carlos Paz personalizado")
  await expect(dialog.locator(".ai-review-row").first().locator(".ai-fare-panel").first().getByLabel("Precio final del proveedor")).toHaveValue("104000")
  await dialog.getByRole("button", { name: "Agregar salida", exact: true }).click()
  await expect(dialog.locator(".ai-review-row")).toHaveCount(7)
  const added = dialog.locator(".ai-review-row").last()
  await added.getByLabel(/^Fecha de salida/).fill("2028-12-20")
  await page.screenshot({ path: testInfo.outputPath("wizard-departures.png") })
  await dialog.getByRole("button", { name: "Continuar al resumen" }).click()
  await expect(dialog.getByText("6 viajes como borradores", { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await dialog.getByRole("button", { name: "Cancelar", exact: true }).click()
  await expect(dialog).toBeHidden()
  await page.reload()
  await page.getByRole("link", { name: "Importar con IA", exact: true }).click()
  await dialog.locator("[data-resume]").first().click()
  await expect(dialog.getByLabel("Hotel", { exact: true })).toHaveValue("Hotel actualizado")
  await dialog.getByRole("button", { name: "Revisar viajes y fechas" }).click()
  await expect(dialog.getByText("6 viajes seleccionados para crear", { exact: true })).toBeVisible()
  await dialog.getByRole("button", { name: "Continuar al resumen" }).click()
  await expect(dialog.getByRole("heading", { name: "Todo listo para crear tus viajes" })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath("wizard-confirmation.png") })
  await dialog.getByRole("button", { name: "Crear 6 viajes como borradores", exact: true }).click()
  await expect(dialog.getByRole("heading", { name: "6 viajes creados correctamente" })).toBeVisible()
  await expect(dialog.getByRole("link", { name: /Abrir borrador/ })).toHaveCount(6)
  await dialog.getByRole("button", { name: "Ver borradores", exact: true }).click()
  await expect(page).toHaveURL(/tab=drafts/)
  await expect(page.getByRole("tab", { name: "Borradores 6", exact: true })).toHaveAttribute("aria-selected", "true")
  await expect(page.locator("tbody tr")).toHaveCount(6)
  await expect(page.locator("tbody tr").first()).toContainText("20/12/2028")
  await expect(page.getByRole("link", { name: "Carlos Paz personalizado", exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test("multi destination layout keeps programs dates and hotel price options separate", async ({ page }, testInfo) => {
  test.setTimeout(120000)
  const dialog = await startWizard(page, testInfo, "GrupoRolSol")
  await dialog.getByLabel("Archivo a importar").setInputFiles(path.join(__dirname, "../fixtures/files/agent_multi_program.jpg"))
  await dialog.getByRole("button", { name: "Procesar con IA", exact: true }).click()
  await expect(dialog.getByRole("heading", { name: "Revisá la información extraída" })).toBeVisible()
  const programs = dialog.locator(".ai-program")
  await expect(programs).toHaveCount(7)
  await expect(programs.first().getByLabel("Nombre de la tarifa")).toHaveValue("Base doble")
  await expect(programs.first().getByLabel("Moneda")).toHaveValue("ARS")
  const hotels = programs.nth(1)
  await hotels.getByRole("tab", { name: "Base doble · Hotel Grand Prix", exact: true }).click()
  await expect(hotels.getByRole("tabpanel", { name: "Base doble · Hotel Grand Prix", exact: true }).getByLabel("Precio final del proveedor")).toHaveValue("14999.00")
  await hotels.getByRole("tab", { name: "Base doble · Hotel Sierrasol", exact: true }).click()
  await expect(hotels.getByRole("tabpanel", { name: "Base doble · Hotel Sierrasol", exact: true }).getByLabel("Precio final del proveedor")).toHaveValue("12999.00")
  await page.screenshot({ path: testInfo.outputPath("wizard-hotel-options.png") })
  await dialog.getByRole("button", { name: "Revisar viajes y fechas" }).click()
  await expect(dialog.locator(".ai-review-row")).toHaveCount(12)
  const undated = dialog.locator(".ai-review-row").filter({ hasText: "Perlas de La Rioja" })
  await undated.getByRole("checkbox").uncheck()
  await expect(dialog.getByText("11 viajes seleccionados para crear", { exact: true })).toBeVisible()
  await dialog.getByRole("button", { name: "Continuar al resumen" }).click()
  await dialog.getByRole("button", { name: "Crear 11 viajes como borradores", exact: true }).click()
  await expect(dialog.getByRole("heading", { name: "11 viajes creados correctamente" })).toBeVisible()
  await dialog.getByRole("button", { name: "Ver borradores", exact: true }).click()
  await expect(page.getByRole("tab", { name: "Borradores 11", exact: true })).toHaveAttribute("aria-selected", "true")
  await expect(page.locator("tbody tr")).toHaveCount(11)
  await expect(page.getByRole("link", { name: "Mina Clavero", exact: true })).toBeVisible()
  await expect(page.getByRole("link", { name: "Carlos Paz", exact: true })).toHaveCount(1)
})
