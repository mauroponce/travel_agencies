const { test, expect } = require("@playwright/test")
const path = require("path")
const base = `http://localhost:${process.env.E2E_PORT || "3100"}`

test("destination selector filters available trips while only the owner sees inactive trips", async ({ page, browser }, testInfo) => {
  const email = testInfo.project.name.startsWith("mobile") ? "agente-buscador-mobile@turistack.local" : "agente-buscador-desktop@turistack.local"
  await page.goto(`${base}/test/sign-in?email=${encodeURIComponent(email)}`)
  const publicUrl = await page.getByRole("link", { name: "Ver mi web ↗" }).getAttribute("href")
  const privateTitle = `Córdoba inactiva ${testInfo.project.name}`
  await page.goto(`${base}/agente/viajes/new`)
  await page.getByLabel("Proveedor", { exact: true }).selectOption({ label: "Proveedor demo" })
  await page.getByLabel("Título del viaje").fill(privateTitle)
  await page.getByLabel("Destino", { exact: true }).fill("Destino privado")
  await page.getByLabel("Fecha de salida").fill("10/08/2027")
  await page.getByLabel("Precio final del proveedor").fill("550000")
  await page.getByRole("button", { name: "Guardar y publicar", exact: true }).click()
  await page.getByRole("button", { name: "Despublicar", exact: true }).click()
  await expect(page.locator(".agent-heading .agent-eyebrow")).toHaveText("Despublicado")
  const flyerTitle = `Córdoba con flyer ${testInfo.project.name}`
  await page.goto(`${base}/agente/viajes/new`)
  await page.getByLabel("Proveedor", { exact: true }).selectOption({ label: "Proveedor demo" })
  await page.getByLabel("Título del viaje").fill(flyerTitle)
  await page.getByLabel("Destino", { exact: true }).fill("Córdoba")
  await page.getByLabel("Fecha de salida").fill("10/08/2027")
  await page.getByLabel("Precio final del proveedor").fill("650000")
  await page.getByLabel("Flyer original", { exact: false }).setInputFiles(path.join(__dirname, "../fixtures/files/agent.png"))
  await page.getByRole("button", { name: "Guardar y publicar", exact: true }).click()
  await expect(page.getByRole("heading", { name: flyerTitle, level: 1, exact: true })).toBeVisible()
  await page.goto(publicUrl)
  await expect(page.getByRole("link", { name: privateTitle, exact: true })).toBeVisible()
  await expect(page.getByText("Despublicado", { exact: true })).toBeVisible()
  await page.goto(`${base}/agente/mi-web/preview`)
  await expect(page.getByRole("link", { name: privateTitle, exact: true })).toHaveCount(0)

  const context = await browser.newContext({ viewport: page.viewportSize() })
  try {
    const visitor = await context.newPage()
    await visitor.goto(publicUrl)
    await expect(visitor.getByRole("link", { name: privateTitle, exact: true })).toHaveCount(0)
    const destination = visitor.getByRole("combobox", { name: "Destino", exact: true })
    await expect(destination).toBeVisible()
    await expect(visitor.getByRole("button", { name: "Buscar viajes", exact: true })).toHaveCount(0)
    await expect(visitor.locator(".agent-public-filters")).toHaveCount(0)
    await destination.click()
    await expect(destination).toHaveAttribute("aria-expanded", "true")
    await expect(visitor.getByRole("option", { name: "Destino privado", exact: true })).toHaveCount(0)
    await expect(visitor.getByRole("option", { name: "Córdoba", exact: true })).toHaveCount(1)
    await destination.fill("sin resultados")
    await expect(visitor.getByRole("status")).toHaveText("No encontramos ese destino. Probá con otro nombre.")
    await destination.press("Enter")
    await expect(visitor).toHaveURL(publicUrl)
    await destination.press("Escape")
    await expect(destination).toHaveAttribute("aria-expanded", "false")
    await expect(destination).toHaveValue("Todos los destinos")
    await destination.fill("cordoba")
    await expect(visitor.getByRole("option", { name: "Córdoba", exact: true })).toBeVisible()
    await visitor.screenshot({ path: `tmp/agent-destination-dropdown-${page.viewportSize().width}.png`, fullPage: true })
    await visitor.getByRole("option", { name: "Córdoba", exact: true }).click()
    await expect(visitor).toHaveURL(/destination=C/)
    await expect(destination).toHaveValue("Córdoba")
    await expect(visitor.getByRole("link", { name: flyerTitle, exact: true })).toBeVisible()
    await expect(visitor.getByRole("link", { name: privateTitle, exact: true })).toHaveCount(0)
    for (const card of await visitor.locator(".agent-trip-card").all()) {
      await expect(card).toContainText("Córdoba")
    }
    expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await visitor.screenshot({ path: `tmp/agent-public-search-${page.viewportSize().width}.png`, fullPage: true })
    await visitor.getByRole("link", { name: flyerTitle, exact: true }).click()
    await expect(visitor.getByRole("heading", { name: flyerTitle, level: 1, exact: true })).toBeVisible()
    await visitor.goBack()
    await expect(destination).toHaveValue("Córdoba")
    await destination.click()
    await expect(visitor.getByRole("option", { name: "Córdoba", exact: true })).toHaveAttribute("aria-selected", "true")
    await destination.press("ArrowDown")
    await expect(destination).toHaveAttribute("aria-activedescendant", "destination-option-0")
    await destination.press("Enter")
    await expect(destination).toHaveValue("Todos los destinos")
    await expect(visitor).toHaveURL(/destination=$/)
    await destination.click()
    await visitor.getByRole("heading", { name: "¿A dónde querés viajar?" }).click()
    await expect(destination).toHaveAttribute("aria-expanded", "false")
    await destination.focus()
    await destination.press("Tab")
    await expect(destination).toHaveAttribute("aria-expanded", "false")
    await expect(visitor.getByRole("link", { name: flyerTitle, exact: true })).toBeVisible()
  } finally {
    await context.close()
  }
})
