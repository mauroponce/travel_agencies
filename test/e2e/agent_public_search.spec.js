const { test, expect } = require("@playwright/test")
const path = require("path")
const base = `http://localhost:${process.env.E2E_PORT || "3100"}`

test("public autocomplete finds available trips while only the owner sees inactive trips", async ({ page, browser }, testInfo) => {
  const email = testInfo.project.name.startsWith("mobile") ? "agente-buscador-mobile@turistack.local" : "agente-buscador-desktop@turistack.local"
  await page.goto(`${base}/test/sign-in?email=${encodeURIComponent(email)}`)
  const publicUrl = await page.getByRole("link", { name: "Ver mi web ↗" }).getAttribute("href")
  const privateTitle = `Córdoba inactiva ${testInfo.project.name}`
  await page.goto(`${base}/agente/viajes/new`)
  await page.getByLabel("Empresa proveedora").selectOption({ label: "Proveedor demo" })
  await page.getByLabel("Título del viaje").fill(privateTitle)
  await page.getByLabel("Destino", { exact: true }).fill("Córdoba")
  await page.getByLabel("Fecha de salida").fill("2027-08-10")
  await page.getByLabel("Precio final del proveedor").fill("550000")
  await page.getByRole("button", { name: "Guardar y publicar", exact: true }).click()
  await page.getByRole("button", { name: "Despublicar", exact: true }).click()
  await expect(page.locator(".agent-heading .agent-eyebrow")).toHaveText("Despublicado")
  const flyerTitle = `Córdoba con flyer ${testInfo.project.name}`
  await page.goto(`${base}/agente/viajes/new`)
  await page.getByLabel("Empresa proveedora").selectOption({ label: "Proveedor demo" })
  await page.getByLabel("Título del viaje").fill(flyerTitle)
  await page.getByLabel("Destino", { exact: true }).fill("Córdoba")
  await page.getByLabel("Fecha de salida").fill("2027-08-10")
  await page.getByLabel("Precio final del proveedor").fill("650000")
  await page.getByLabel("Flyer original", { exact: false }).setInputFiles(path.join(__dirname, "../fixtures/files/agent.png"))
  await page.getByRole("button", { name: "Guardar y publicar", exact: true }).click()
  await expect(page.getByRole("heading", { name: flyerTitle, level: 1, exact: true })).toBeVisible()
  await page.goto(publicUrl)
  await expect(page.getByRole("link", { name: privateTitle, exact: true })).toBeVisible()
  await expect(page.getByText("Despublicado", { exact: true })).toBeVisible()
  await page.goto(`${base}/agente/mi-web/preview`)
  await expect(page.getByRole("link", { name: privateTitle, exact: true })).toHaveCount(0)

  const context = await browser.newContext({ viewport: page.viewportSize() })
  try {
    const visitor = await context.newPage()
    await visitor.goto(publicUrl)
    await expect(visitor.getByRole("link", { name: privateTitle, exact: true })).toHaveCount(0)
    const input = visitor.getByRole("combobox", { name: "Buscar destino o viaje" })
    await input.fill("C")
    await expect(input).toHaveAttribute("aria-expanded", "false")
    await input.fill("Cor")
    await expect(visitor.getByRole("option", { name: /Escapada a Córdoba/ })).toBeVisible()
    await expect(visitor.getByRole("option", { name: new RegExp(privateTitle) })).toHaveCount(0)
    await expect(visitor.getByRole("option").first()).toContainText("Salida")
    const flyerOption = visitor.getByRole("option", { name: new RegExp(flyerTitle) })
    await expect(flyerOption.locator("img")).toHaveJSProperty("naturalWidth", 1)
    await expect(flyerOption.locator("strong")).toHaveText("Córdoba")
    await expect(flyerOption).toContainText("Salida 10/08/2027")
    const thumbnail = await flyerOption.locator("img").boundingBox()
    const details = await flyerOption.locator(".agent-search-option-body").boundingBox()
    expect(thumbnail.x + thumbnail.width).toBeLessThan(details.x)
    expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await visitor.screenshot({ path: `tmp/agent-public-search-${page.viewportSize().width}.png`, fullPage: true })

    await input.press("ArrowDown")
    await expect(visitor.getByRole("option").first()).toHaveAttribute("aria-selected", "true")
    await input.press("Escape")
    await expect(input).toHaveAttribute("aria-expanded", "false")
    await input.fill("ZZZsinresultados")
    await expect(visitor.getByRole("status")).toContainText("No encontramos viajes vigentes")
    await visitor.getByRole("button", { name: "Borrar búsqueda" }).click()
    await expect(input).toHaveValue("")
    await expect(input).toBeFocused()
    await expect(input).toHaveAttribute("aria-expanded", "false")

    await input.fill("cordoba")
    await flyerOption.click()
    await expect(visitor).toHaveURL(/\/viajes\//)
    await expect(visitor.getByRole("heading", { name: flyerTitle, level: 1, exact: true })).toBeVisible()
    await visitor.goBack()
    await input.fill("Cor")
    await expect(visitor.getByRole("option").first()).toBeVisible()
    await input.press("ArrowDown")
    await input.press("Enter")
    await expect(visitor).toHaveURL(/\/viajes\//)
    await expect(visitor.getByRole("heading", { name: "Escapada a Córdoba", level: 1, exact: true })).toBeVisible()
    await visitor.goto(publicUrl)

    await visitor.route("**/buscar-viajes?*", route => route.fulfill({ status: 503, body: "Unavailable" }))
    await input.fill("Cor")
    await expect(visitor.getByRole("status")).toContainText("No pudimos cargar las sugerencias")
    await visitor.getByRole("button", { name: "Buscar viajes", exact: true }).click()
    await expect(visitor).toHaveURL(/q=Cor/)
    await expect(visitor.locator(".agent-trip-card").first()).toContainText("Escapada a Córdoba")
    await expect(visitor.getByRole("link", { name: privateTitle, exact: true })).toHaveCount(0)
  } finally {
    await context.close()
  }
})
