const { test, expect } = require("@playwright/test")
const path = require("path")
const base = `http://localhost:${process.env.E2E_PORT || "3100"}`

test("agent chooses public sections and publishes a personal introduction with a photo", async ({ page, browser }, testInfo) => {
  const email = testInfo.project.name.startsWith("mobile") ? "agente-web-mobile@turistack.local" : "agente-web-desktop@turistack.local"
  await page.goto(`${base}/test/sign-in?email=${encodeURIComponent(email)}`)
  await page.goto(`${base}/asesor/mi-web`)
  const aboutToggle = page.getByRole("checkbox", { name: /Sobre mí/ })
  const catalogToggle = page.getByRole("checkbox", { name: /^Viajes/ })
  const text = "Soy Lucía. Me encanta ayudarte a descubrir nuevos destinos.\nTe acompaño antes, durante y después de tu viaje."
  await expect(aboutToggle).not.toBeChecked()
  await expect(page.getByLabel("Texto sobre mí")).toBeHidden()
  await expect(catalogToggle).toBeChecked()
  await aboutToggle.check()
  await expect(page.getByLabel("Texto sobre mí")).toBeVisible()
  await page.getByLabel("Texto sobre mí").fill(text)
  await page.getByLabel("Tu foto", { exact: true }).setInputFiles(path.join(__dirname, "../fixtures/files/agent.jpg"))
  await expect(page.locator(".agent-photo-preview")).toBeVisible()
  await expect(page.locator(".agent-photo-preview")).toHaveJSProperty("naturalWidth", 1)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole("button", { name: "Guardar cambios", exact: true }).click()
  await expect(aboutToggle).toBeChecked()
  await expect(page.getByLabel("Texto sobre mí")).toHaveValue(text)
  const preview = page.frameLocator('iframe[title="Vista previa del catálogo"]')
  await expect(preview.locator("#sobre-mi")).toBeVisible()
  await expect(preview.locator("#sobre-mi .agent-about-text")).toHaveText(text)
  const publicUrl = await page.getByRole("link", { name: "Abrir mi web ↗" }).getAttribute("href")

  const visitorContext = await browser.newContext({ viewport: page.viewportSize() })
  try {
    const visitor = await visitorContext.newPage()
    await visitor.goto(publicUrl)
    await expect(visitor.getByRole("heading", { name: "Sobre mí", exact: true })).toBeVisible()
    await expect(visitor.locator("#presentacion")).toHaveCount(0)
    const whatsapp = visitor.getByRole("link", { name: "Consultar por WhatsApp", exact: true })
    await expect(whatsapp).toBeVisible()
    await expect(whatsapp).toHaveAttribute("href", /^https:\/\/wa\.me\//)
    await expect(whatsapp).toHaveCSS("position", "fixed")
    const beforeScroll = await whatsapp.boundingBox()
    expect(beforeScroll.x + beforeScroll.width).toBeLessThanOrEqual(visitor.viewportSize().width)
    expect(beforeScroll.y + beforeScroll.height).toBeLessThanOrEqual(visitor.viewportSize().height)
    expect(visitor.viewportSize().width - beforeScroll.x - beforeScroll.width).toBeLessThanOrEqual(24)
    expect(visitor.viewportSize().height - beforeScroll.y - beforeScroll.height).toBeLessThanOrEqual(24)
    await visitor.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
    await expect(whatsapp).toBeVisible()
    const afterScroll = await whatsapp.boundingBox()
    expect(afterScroll.x).toBe(beforeScroll.x)
    expect(afterScroll.y).toBe(beforeScroll.y)
    await expect(visitor.locator("#sobre-mi .agent-about-text")).toHaveText(text)
    await expect(visitor.locator("#sobre-mi img")).toHaveJSProperty("naturalWidth", 1)
    expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(visitor.locator("#sobre-mi a")).toHaveAttribute("href", /^https:\/\/wa\.me\//)
    await page.screenshot({ path: `tmp/website-settings-${page.viewportSize().width}.png`, fullPage: true })
    await visitor.screenshot({ path: `tmp/website-public-${page.viewportSize().width}.png`, fullPage: true })
    const photoUrl = await visitor.locator("#sobre-mi img").getAttribute("src")

    await aboutToggle.uncheck()
    await catalogToggle.uncheck()
    await expect(page.getByLabel("Texto sobre mí")).toBeHidden()
    await Promise.all([
      page.waitForResponse(response => ["POST", "PATCH"].includes(response.request().method()) && new URL(response.url()).pathname === "/asesor/mi-web"),
      page.getByRole("button", { name: "Guardar cambios", exact: true }).click()
    ])
    await visitor.reload()
    await expect(visitor.locator("#sobre-mi, #presentacion, #viajes")).toHaveCount(0)
    await expect(whatsapp).toBeVisible()
    expect((await visitor.request.get(photoUrl)).status()).toBe(404)
    await aboutToggle.check()
    await expect(page.getByLabel("Texto sobre mí")).toHaveValue(text)
  } finally {
    await visitorContext.close()
    await catalogToggle.check()
    await aboutToggle.uncheck()
    await Promise.all([
      page.waitForResponse(response => ["POST", "PATCH"].includes(response.request().method()) && new URL(response.url()).pathname === "/asesor/mi-web"),
      page.getByRole("button", { name: "Guardar cambios", exact: true }).click()
    ])
  }
})
